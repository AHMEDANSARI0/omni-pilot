#!/usr/bin/env node
/**
 * Generates the VAPID key pair web push needs, in the exact format the app expects.
 *
 *   node scripts/vapid-keys.mjs           print the three values
 *   node scripts/vapid-keys.mjs --write   append them to .env.local (never overwrites an existing key)
 *
 * Run this ONCE per project. The pair identifies your app to the push services (Chrome, Safari, Firefox);
 * every device that subscribed is tied to it. Regenerating invalidates every existing subscription, so the
 * script refuses to overwrite keys that are already set.
 *
 * Without these keys everything else still works: the API reports push as `configured: false`, the
 * dashboard hides the button, and approval emails keep arriving.
 */
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, readFileSync, appendFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const ENV_PATH = join(ROOT, '.env.local');
const write = process.argv.includes('--write');

/**
 * A VAPID key pair is P-256: the private key is the raw 32-byte scalar, the public key is the raw
 * 65-byte uncompressed point (0x04 || X || Y), both base64url encoded without padding.
 */
function generate() {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  // JWK is the one export that hands over the raw scalars, so nothing has to be sliced out of ASN.1.
  const priv = privateKey.export({ format: 'jwk' });
  const pub = publicKey.export({ format: 'jwk' });
  if (!priv.d || !pub.x || !pub.y) throw new Error('unexpected key export - no scalar/point present');

  const d = Buffer.from(priv.d, 'base64url');
  const x = Buffer.from(pub.x, 'base64url');
  const y = Buffer.from(pub.y, 'base64url');
  if (d.length !== 32) throw new Error(`private key is ${d.length} bytes, expected 32`);

  // Uncompressed P-256 point: 0x04 || X || Y. This is the form the Push API wants.
  const point = Buffer.concat([Buffer.from([0x04]), x, y]);
  if (point.length !== 65) throw new Error(`public key is ${point.length} bytes, expected 65`);

  return {
    publicKey: point.toString('base64url'),
    privateKey: d.toString('base64url'),
  };
}

const existing = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, 'utf8') : '';
const alreadySet = /^\s*VAPID_(PUBLIC|PRIVATE)_KEY\s*=\s*\S/m.test(existing);

if (alreadySet) {
  console.log('\n  VAPID keys are already set in .env.local - nothing to do.');
  console.log('  Regenerating them would invalidate every device that has already subscribed.');
  console.log('  If you really want new keys: delete the VAPID lines first, then run this again.\n');
  process.exit(0);
}

const pair = generate();
const subject = 'mailto:you@example.com';
const block = [
  '',
  '# Web push (Phase 10). Generated by scripts/vapid-keys.mjs - do not regenerate once devices',
  '# have subscribed: the keys identify the app to the push service.',
  `VAPID_PUBLIC_KEY=${pair.publicKey}`,
  `VAPID_PRIVATE_KEY=${pair.privateKey}`,
  `VAPID_SUBJECT=${subject}`,
  '',
].join('\n');

console.log('\n  VAPID key pair (P-256, base64url, verified)');
console.log(`\n  VAPID_PUBLIC_KEY=${pair.publicKey}`);
console.log(`  VAPID_PRIVATE_KEY=${pair.privateKey}`);
console.log(`  VAPID_SUBJECT=${subject}        <- change to your own mailto:`);

if (write) {
  appendFileSync(ENV_PATH, block, 'utf8');
  console.log(`\n  appended to ${ENV_PATH}`);
  console.log('  Next: set the same three values in your deployment (Cloudflare secrets), then deploy.');
  console.log('  Then open Settings -> Account -> Enable notifications on the phone.\n');
} else {
  console.log('\n  Add these to .env.local (or run again with --write to append them):');
  console.log('    node scripts/vapid-keys.mjs --write\n');
}
