#!/usr/bin/env node
/**
 * Creates a ready-to-run .env.local for local development (all external services stubbed).
 *
 *   node scripts/init-env.mjs                 # owner@example.com
 *   node scripts/init-env.mjs you@gmail.com   # your own owner email
 *   node scripts/init-env.mjs --force         # overwrite an existing .env.local
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '.env.local');
const args = process.argv.slice(2);
const force = args.includes('--force');
const ownerEmail = args.find((arg) => !arg.startsWith('--')) ?? 'owner@example.com';

if (existsSync(target) && !force) {
  console.log('.env.local already exists - nothing changed. Use --force to regenerate it.');
  process.exit(0);
}

if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(ownerEmail)) {
  console.error(`"${ownerEmail}" does not look like an email address.`);
  process.exit(1);
}

const env = `# Generated by scripts/init-env.mjs - local development only.
# SERVICES_MODE=local stubs Google Sheets, Gemini, Resend and LinkedIn, so nothing
# is really sent or published. ALLOW_DEV_BYPASS removes the login screen on localhost.
APP_ENV=development
APP_BASE_URL=http://localhost:8787
OWNER_EMAIL=${ownerEmail}
PORT=8787

# secrets (randomly generated, local only)
APPROVAL_TOKEN_SECRET=${randomBytes(32).toString('hex')}
TOKEN_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}
CRON_SECRET=${randomBytes(24).toString('hex')}

SERVICES_MODE=local
ALLOW_DEV_BYPASS=true
DEV_CRON=true

# --- switch to live later: replace the block below and set SERVICES_MODE=live ---
# SUPABASE_URL=
# SUPABASE_ANON_KEY=
# SUPABASE_SERVICE_ROLE_KEY=
# GEMINI_API_KEY=
# GOOGLE_CLIENT_ID=
# GOOGLE_CLIENT_SECRET=
# GOOGLE_SHEET_ID=
# GOOGLE_SHEET_TAB=Content
# RESEND_API_KEY=
# RESEND_FROM_EMAIL=LinkedIn Automation <onboarding@resend.dev>
# LINKEDIN_CLIENT_ID=
# LINKEDIN_CLIENT_SECRET=
# LINKEDIN_API_VERSION=202506
`;

writeFileSync(target, env, 'utf8');
console.log(`Created ${target}`);
console.log(`Owner: ${ownerEmail}`);
console.log(`
Next steps:
  1. npm run build        # builds the static dashboard into ./out
  2. npm run dev:api      # API + dashboard on http://localhost:8787
     (or "npm run dev" for hot reload on http://localhost:3000)

The dashboard opens without a login because ALLOW_DEV_BYPASS=true.
Dev emails are captured in the local outbox: GET /api/v1/integrations/dev/outbox`);
