#!/usr/bin/env node
/**
 * Builds one paste-ready SQL file from `supabase/migrations/`.
 *
 *   node tools/build-setup-sql.mjs
 *
 * Why. Applying the schema by hand means pasting five files into the Supabase SQL Editor in order, and the
 * two ways that goes wrong are both silent: paste them out of order and a function references a table that
 * does not exist yet (`0005` calls `set_updated_at()` from `0001`/`0002`), or miss one and `db:verify` fails
 * with a list of objects that are simply absent.
 *
 * This concatenates them in filename order, with a visible banner before each file, into a single statement
 * stream that can be pasted once. It is still the same SQL - no rewriting, no filtering - so the result is
 * exactly what `scripts/db-push.mjs` would send, and still idempotent: every file is `if not exists` /
 * `create or replace` guarded.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const DIR = join(ROOT, 'supabase', 'migrations');
const OUT_DIR = join(ROOT, 'supabase');
const OUT = join(OUT_DIR, 'setup.sql');

const files = readdirSync(DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  console.error('no .sql files in supabase/migrations');
  process.exit(1);
}

const parts = [
  `-- setup.sql - every migration, in order, for one paste into the Supabase SQL Editor.`,
  `--`,
  `-- Generated by tools/build-setup-sql.mjs from supabase/migrations/. Do not edit by hand: change the`,
  `-- numbered file and rebuild, so this cannot drift from what the app expects.`,
  `--`,
  `-- Files in order: ${files.join(', ')}.`,
  `--`,
  `-- Safe to run more than once: every statement is "if not exists" / "create or replace". If you are`,
  `-- re-running after a partial paste, nothing is duplicated and nothing is dropped.`,
  ``,
];

let statements = 0;
for (const name of files) {
  const body = readFileSync(join(DIR, name), 'utf8').replace(/\r\n/g, '\n');
  const lines = body.split('\n').length;
  statements += (body.match(/;\s*$/gm) ?? []).length;
  parts.push(
    `-- ${'='.repeat(96)}`,
    `-- ${name}   (${lines} lines)`,
    `-- ${'='.repeat(96)}`,
    ``,
    body.trimEnd(),
    ``,
  );
}

const output = `${parts.join('\n')}\n`;
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, output);

console.log(
  `supabase/setup.sql written - ${files.length} migrations, ${(output.length / 1024).toFixed(0)} kB, ` +
    `${statements} statements`,
);
console.log(`  ${files.map((name) => name.replace('_', ' ').replace('.sql', '')).join(' -> ')}`);
